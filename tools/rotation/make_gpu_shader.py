#!/usr/bin/env python3
"""Generate a minimal SPIR-V 1.0 compute permutation; no runtime shader translator."""
from pathlib import Path
words=[]
ids={}
def ident(name):
    if name not in ids:ids[name]=len(ids)+1
    return ids[name]
def emit(op,*operands):words.append(((len(operands)+1)<<16)|op);words.extend(operands)
def ref(op,*names):emit(op,*(ident(n) if isinstance(n,str) else n for n in names))
def string(value):
    data=value.encode()+b'\0';data+=b'\0'*((-len(data))%4)
    return [int.from_bytes(data[i:i+4],'little') for i in range(0,len(data),4)]
emit(17,1) # Shader
emit(14,0,1) # Logical GLSL450
emit(15,5,ident('main'),*string('main'),ident('invocation'))
ref(16,'main',17,8,8,1)
ref(71,'words',6,4) # ArrayStride
ref(72,'storage',0,35,0)
ref(71,'storage',3) # BufferBlock, Uniform storage class (SPIR-V 1.0)
ref(71,'source',34,0);ref(71,'source',33,0)
ref(71,'destination',34,0);ref(71,'destination',33,1)
ref(71,'push',2)
for i in range(4):ref(72,'push',i,35,i*4)
ref(71,'invocation',11,28) # BuiltIn GlobalInvocationId
ref(19,'void');ref(20,'bool');ref(21,'uint',32,0);ref(23,'uvec3','uint',3)
ref(29,'words','uint');ref(30,'storage','words')
ref(32,'storageptr',2,'storage');ref(32,'wordptr',2,'uint')
ref(30,'push','uint','uint','uint','uint');ref(32,'pushptr',9,'push');ref(32,'pushword',9,'uint')
ref(32,'inputptr',1,'uvec3');ref(33,'function','void')
for i in range(4):ref(43,'uint',f'c{i}',i)
ref(59,'storageptr','source',2);ref(59,'storageptr','destination',2)
ref(59,'pushptr','parameters',9);ref(59,'inputptr','invocation',1)
ref(54,'void','main',0,'function');ref(248,'entry')
ref(61,'uvec3','gid','invocation');ref(81,'uint','x','gid',0);ref(81,'uint','y','gid',1)
for i,name in enumerate(['width','height','source_pitch','destination_pitch']):
    ref(65,'pushword',name+'_ptr','parameters',f'c{i}');ref(61,'uint',name,name+'_ptr')
ref(176,'bool','x_ok','x','width');ref(176,'bool','y_ok','y','height');ref(167,'bool','inside','x_ok','y_ok')
ref(247,'end',0);ref(250,'inside','copy','end');ref(248,'copy')
ref(130,'uint','last_x','width','c1');ref(130,'uint','last_y','height','c1')
ref(130,'uint','sx','last_x','x');ref(130,'uint','sy','last_y','y')
ref(132,'uint','source_row','sy','source_pitch');ref(128,'uint','source_index','source_row','sx')
ref(132,'uint','destination_row','y','destination_pitch');ref(128,'uint','destination_index','destination_row','x')
ref(65,'wordptr','source_address','source','c0','source_index');ref(61,'uint','pixel','source_address')
ref(65,'wordptr','destination_address','destination','c0','destination_index');ref(62,'destination_address','pixel')
ref(249,'end');ref(248,'end');emit(253);emit(56)
module=[0x07230203,0x00010000,0,len(ids)+1,0]+words
out=Path(__file__).resolve().with_name('gpu_shader.h')
rows=['/* Generated by make_gpu_shader.py: raw uint32 180-degree copy, 8x8 workgroups. */','#pragma once','#include <stdint.h>','static const uint32_t nmRotationGPUShader[] = {']
rows+=['    '+', '.join(f'0x{x:08x}u' for x in module[i:i+8])+',' for i in range(0,len(module),8)]
rows+=['};','']
out.write_text('\n'.join(rows))
if __name__=='__main__':print(f'{len(module)} words, bound {len(ids)+1}')
